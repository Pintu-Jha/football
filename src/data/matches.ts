export function getMatchBySlug(slug: string): Match | undefined {
  return matches.find((m) => m.slug === slug)
}

export function getMatchesByCompetition(competitionId: string): Match[] {
  return matches.filter((m) => m.competitionId === competitionId)
}

const moreMatchOrder: Record<string, string[]> = {
  championship: [
    'leeds-vs-west-brom',
    'norwich-vs-cardiff',
    'sunderland-vs-sheffield-united',
  ],
}

export function getMoreMatches(match: Match, count = 3): Match[] {
  const others = getMatchesByCompetition(match.competitionId).filter(
    (m) => m.slug !== match.slug,
  )
  const preferred = moreMatchOrder[match.competitionId]
  if (!preferred) {
    return others.slice(0, count)
  }
  const ordered = preferred
    .map((slug) => others.find((m) => m.slug === slug))
    .filter((m): m is Match => Boolean(m))
  const rest = others.filter((m) => !preferred.includes(m.slug))
  return [...ordered, ...rest].slice(0, count)
}

